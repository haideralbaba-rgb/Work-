export async function seedBusiness(userId: string, target: number) {
  const existingPhases = await db
    .select({ id: roadmapPhases.id })
    .from(roadmapPhases)
    .where(eq(roadmapPhases.userId, userId));
  if (existingPhases.length === 0) {
    for (const def of PHASE_DEFS) {
      const [phase] = await db
        .insert(roadmapPhases)
        .values({
          userId,
          idx: def.idx,
          key: def.key,
          titleAr: def.titleAr,
          titleEn: def.titleEn,
          objectiveAr: def.objectiveAr,
          unlockRule: def.unlockRule,
          status: def.idx === 1 ? "active" : "locked",
        })
        .returning();
      await db.insert(roadmapTasks).values(
        def.tasks.map((t, i) => ({
          phaseId: phase.id,
          userId,
          idx: i + 1,
          titleAr: t.titleAr,
          descAr: t.descAr,
          evidenceHint: t.evidenceHint,
        }))
      );
    }
  }
  const existingGoal = await db.select({ id: goals.id }).from(goals).where(eq(goals.userId, userId));
  if (existingGoal.length === 0) {
    await db.insert(goals).values({ userId, target: String(target || 2000) });
  }
}
